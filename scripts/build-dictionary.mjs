// Generates src/data/dictionary.ts from the `word-list` package (MIT, ~274k English words).
// Run with `npm run dictionary` after upgrading word-list. Output is committed so the
// app has no runtime dependency on the package.
import { readFileSync, writeFileSync } from 'node:fs'
import wordListPath from 'word-list'

const words = readFileSync(wordListPath, 'utf8').split('\n')
const ofLength = (n) => words.filter((w) => new RegExp(`^[a-z]{${n}}$`).test(w)).join(' ').toUpperCase()

const out = `// AUTO-GENERATED by scripts/build-dictionary.mjs — do not edit by hand.
// Valid guesses, space-separated to keep the bundle small.
export const FIVE_LETTER_WORDS = '${ofLength(5)}'
export const THREE_LETTER_WORDS = '${ofLength(3)}'
`
writeFileSync(new URL('../src/data/dictionary.ts', import.meta.url), out)
console.log('Wrote src/data/dictionary.ts')
